        function g=group(name)
            if startsWith(name,'stage2_zlp_refine_'),g='Stage2 ZLP';
            elseif contains(name,'attention')||contains(name,'sigmoid')||contains(name,'hard_be_pair'),g='Attention and BE selection';
            elseif contains(name,'pm_')||contains(name,'em_')||strcmp(name,'stage2_soft_be_weight')||strcmp(name,'stage1_be_soft_scale')||contains(name,'dense_'),g='PM and EM';
            elseif contains(name,'zlp')||contains(name,'initial_width'),g='Stage1 ZLP';
            else,g='Data weights';end
        end
        function tf=isInteger(names)
            tf=strcmp(names,'stage1_zlp_gain_asym_prior_start_index');
        end
        function reason=inactive(name,s)
            reason='';pairs={ ...
                'stage1_zlp_fartail_', 'stage1_zlp_core_fartail_enabled'; ...
                'stage1_zlp_core_', 'stage1_zlp_core_fartail_enabled'; ...
                'stage1_zlp_gain_tail_', 'stage1_zlp_gain_tail_prior_enabled'; ...
                'stage1_zlp_gain_asym_', 'stage1_zlp_gain_asym_shape_prior_enabled'; ...
                'zlp_signal_guard_', 'zlp_signal_guard_enabled'; ...
                'zlp_lowfreq_guard_', 'zlp_lowfreq_guard_enabled'; ...
                'em_lowfreq_dense_', 'em_lowfreq_dense_enabled'; ...
                'stage2_soft_dense_', 'stage2_soft_dense_em_enabled'; ...
                'stage2_attention_', 'stage2_attention_enabled'; ...
                'stage2_far_tail_', 'stage2_far_tail_downweight_enabled'; ...
                'stage2_zlp_refine_', 'stage2_zlp_refine_enabled'};
            for j=1:size(pairs,1)
                if startsWith(name,pairs{j,1})&&~s.(pairs{j,2}),reason=['requires ',pairs{j,2}];return;end
            end
            if contains(name,'gain_shape_heavy')||contains(name,'loss_shape_light')
                if ~s.stage1_zlp_gain_heavy_init_enabled,reason='requires stage1_zlp_gain_heavy_init_enabled';end
            end
            if startsWith(name,'stage2_hard_be_pair')&&(~isempty(s.stage2_fixed_hard_be_window_meV)||~s.stage2_attention_hardbe_only_enabled)
                reason='fixed hard window or all-hard mode overrides pair selection';
            end
            if startsWith(name,'stage2_far_tail_loss_budget')&&~s.stage2_far_tail_loss_budget_downweight_enabled,reason='loss-budget weighting disabled';end
        end
        function [ok,why]=available(p,s)
            ok=true(1,numel(p));why=repmat({''},1,numel(p));
            for j=1:numel(p)
                try,EELS_TuningSearch.validateActive(p(j),s);catch ME,ok(j)=false;why{j}=ME.message;end
            end
        end
        function t=inventory(s)
            p=EELS_ReferenceTuner.parameters();[ok,why]=EELS_ParameterCatalog.available(p,s);
            names=fieldnames(s);value=cell(size(names));kind=value;group=value;reason=value;
            for j=1:numel(names)
                name=names{j};v=s.(name);try,value{j}=jsonencode(v);catch,value{j}='<runtime object>';end
                k=find(strcmp({p.name},name),1);group{j}='Configuration';
                if ~isempty(k)
                    group{j}=EELS_ParameterCatalog.group(name);kind{j}='continuous PSO';
                    if EELS_ParameterCatalog.isInteger({name}),kind{j}='integer PSO';end
                    reason{j}='available (conditional numerical sensitivity is not guaranteed)';
                    if ~ok(k),reason{j}=why{k};kind{j}='inactive';end
                elseif islogical(v)||ischar(v)||isstring(v)
                    kind{j}='configuration / model choice';reason{j}='fixed within each search; configure before fitting';
                elseif ~isscalar(v)||isstruct(v)||iscell(v)
                    kind{j}='structured configuration';reason{j}='requires coupled bounds or model/round configuration; not an independent PSO scalar';
                else
                    kind{j}='fixed / not registered';reason{j}='not automatically searched; no audited independent search bounds';
                end
                if ismember(name,{'em_step_meV','lambda_be_soft'})
                    reason{j}='Stage1 rounds override base value: tune stage1_em_step_scale / stage1_be_soft_scale';
                elseif isempty(k)&&any(startsWith(name,{'spatial_','stage1_spatial_','stage1_cluster_','stage1_zlp_interface_','stage1_hierarch','stage2_spatial_map_'}))
                    kind{j}='spatial configuration';reason{j}='requires map/neighborhood context; not searched in independent-spectrum calibration';
                elseif isempty(k)&&any(startsWith(name,{'pm_deconv_','pm_interp_','rl_deconv_'}))
                    kind{j}='other analysis configuration';reason{j}='deconvolution/interpolation workflow; outside this Stage1/2 calibration search';
                elseif ismember(name,{'stage2_profile_cost_weight','stage2_joint_rmse_cost_weight','stage2_attention_cost_weight','stage2_regularization_cost_weight'})
                    kind{j}='fixed score definition';reason{j}='kept fixed for comparison of temperature valleys across candidates';
                elseif isempty(k)&&any(startsWith(name,{'datacube_','test_'}))
                    kind{j}='execution / preprocessing configuration';reason{j}='fixed for the sampled calibration dataset, not a PSO action';
                elseif any(contains(name,{'save_','plot','parallel','output','silent','solver','max_nonlinear','early_stop','strict_polish','temperature_refine','adaptive_grid','stage2_T_grid'}))
                    kind{j}='fixed numerical / runtime / diagnostic';reason{j}='configure outside calibration; not optimized against temperature labels';
                end
            end
            t=table(string(names),string(value),string(kind),string(group),string(reason), ...
                'VariableNames',{'parameter','value_JSON','type','group','reason'});
        end
    end
end
