                'stage1_zlp_gain_tail_prior_weight',1e-6,.1; ...
                'stage1_zlp_gain_shape_heavy_factor',.4,2; 'stage1_zlp_loss_shape_light_factor',.4,2; ...
                'stage1_zlp_fartail_data_weight',.02,2; 'stage1_zlp_fartail_anchor_weight',1e-5,.1; ...
                'stage1_zlp_core_anchor_width_meV',3,25; ...
